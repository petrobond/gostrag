def format_documents(items: list[dict]) -> str:
    blocks = []
    headings = [
        f"{item['clause']} {item.get('clause_title', '')}".strip()
        for item in items
        if item.get("clause_title")
    ]
    if len(headings) >= 4:
        blocks.append("Пункты в контексте: " + "; ".join(headings))
    for idx, item in enumerate(items, start=1):
        blocks.append(
            f"[{idx}] ГОСТ: {item['gost_number']}; пункт: {item['clause']}; "
            f"заголовок: {item.get('clause_title', '')}; страница: {item['page']}; "
            f"раздел: {item.get('section_title', '')}\n"
            f"{item['text']}"
        )
    return "\n\n".join(blocks)
